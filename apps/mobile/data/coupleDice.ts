// Couple Dice: three dice faces (mood, action, moment) combine into a
// natural-language, consent-forward prompt. Every mood×action pair has an
// explicit EN/ES template with a `{{moment}}` slot, so no combination can be
// grammatically broken — there is no runtime string concatenation of parts
// that were never checked together.
export type DiceMood = 'playful' | 'connected' | 'romantic' | 'adventurous';
export type DiceAction = 'talk' | 'compliment' | 'choose' | 'explore' | 'plan';
export type DiceMoment =
  | 'right_now'
  | 'this_evening'
  | 'this_week'
  | 'next_date_night';
export type DiceLanguage = 'en' | 'es';

export const DICE_MOODS: DiceMood[] = [
  'playful',
  'connected',
  'romantic',
  'adventurous',
];
export const DICE_ACTIONS: DiceAction[] = [
  'talk',
  'compliment',
  'choose',
  'explore',
  'plan',
];
export const DICE_MOMENTS: DiceMoment[] = [
  'right_now',
  'this_evening',
  'this_week',
  'next_date_night',
];

