export function buildDicePrompt(
  mood: DiceMood,
  action: DiceAction,
  moment: DiceMoment,
  language: DiceLanguage = 'en'
): string {
  const templates = TEMPLATES[language] ?? TEMPLATES.en;
  const momentText = (MOMENT_TEXT[language] ?? MOMENT_TEXT.en)[moment];
  const key = `${mood}:${action}`;
  const template = templates[key];
  if (!template) {
    throw new Error(`Missing Couple Dice template for combination: ${key}`);
  }
  return template(momentText);
}
